#!/usr/bin/env bash
# theme-hook: rofi
# Writes ~/.config/rofi/colors.rasi, only if rofi's config folder exists and the file is one the shell wrote.
set -uo pipefail
source "$(dirname "$(readlink -f "$0")")/../hook-lib.sh"

# Only a file this hook wrote is replaced (the marker on line 1, or the
# older "/* <theme> */" + selected-text format): a user's own colors.rasi,
# with other variables, is left alone.
rofi_colors="$CFG/rofi/colors.rasi"
rofi_marker="/* generated by the shell's theme switch"
rasi="$rofi_marker: $NAME */
* {
    background:     $BG;
    foreground:     $FG;
    selection:      $SELECTION;
    comment:        $COMMENT;
    accent:         $BLUE;
    selected-text:  $BG;
}"
[[ -d "$(dirname "$rofi_colors")" ]] || exit 0
if [[ -e $rofi_colors ]] && [[ $(head -n1 "$rofi_colors") != "$rofi_marker"* ]] \
    && ! { [[ $(head -n1 "$rofi_colors") == "/* "*" */" ]] && grep -q "selected-text:" "$rofi_colors"; }; then
    exit 0   # the user's own file
fi
if [[ ! -f $rofi_colors || $(<"$rofi_colors") != "$rasi" ]]; then
    rm -f "$rofi_colors"   # it may be a symlink (e.g. from a dotfiles repo); the theme copy is generated
    printf '%s\n' "$rasi" > "$rofi_colors"
fi
exit 0
